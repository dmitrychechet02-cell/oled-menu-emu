def rows_to_columns(rows):
    """Строки-картинку -> список байт-столбцов (бит 0 = верхняя строка)."""
    height = len(rows)
    assert height <= 8, rows
    width = len(rows[0])
    cols = []
    for x in range(width):
        b = 0
        for y in range(height):
            assert len(rows[y]) == width, rows
            if rows[y][x] == "#":
                b |= 1 << y
        cols.append(b)
    return cols


def glyph(ch):
    src = GLYPHS.get(ch)
    if src is None and ch in SAME_AS_LATIN:
        src = GLYPHS[SAME_AS_LATIN[ch]]
    if src is None:
        raise KeyError(f"нет глифа для {ch!r}")
    rows = src.split("|")
    assert len(rows) == 7 and all(len(r) == 5 for r in rows), ch
    return rows_to_columns(rows)


def fmt_bytes(cols):
    return ", ".join(f"0x{b:02X}" for b in cols)


def gen_font():
    out = [
        "/* АВТОГЕНЕРАЦИЯ: tools/gen_font.py. Не редактировать вручную. */",
        '#include "font5x7.h"',
        "",
        "/* ASCII 0x20..0x7E */",
        "const uint8_t font5x7_ascii[FONT5X7_ASCII_COUNT][FONT5X7_WIDTH] = {",
    ]
    for cp in range(0x20, 0x7F):
        ch = chr(cp)
        label = hex(cp) if ch in "*/\\" else ch
        out.append(f"    {{{fmt_bytes(glyph(ch))}}}, /* {label} */")
    out += ["};", "", "/* Кириллица U+0410..U+044F (А..я) */",
            "const uint8_t font5x7_cyr[FONT5X7_CYR_COUNT][FONT5X7_WIDTH] = {"]
    for cp in range(0x0410, 0x0450):
        ch = chr(cp)
        out.append(f"    {{{fmt_bytes(glyph(ch))}}}, /* {ch} */")
    out += ["};", "",
            "const font5x7_extra_t font5x7_extra[FONT5X7_EXTRA_COUNT] = {"]
    extras = [("Ё", 0x0401), ("ё", 0x0451), ("°", 0x00B0)]
    for ch, cp in extras:
        out.append(f"    {{0x{cp:04X}, {{{fmt_bytes(glyph(ch))}}}}}, /* {ch} */")
    fb = rows_to_columns(FALLBACK.split("|"))
    out += ["};", "", f"const uint8_t font5x7_fallback[FONT5X7_WIDTH] = {{{fmt_bytes(fb)}}};", ""]
    (ROOT / "src/fonts/font5x7_data.c").write_text("\n".join(out), encoding="utf-8")
    return len(extras)


def gen_icons():
    out = [
        "/* АВТОГЕНЕРАЦИЯ: tools/gen_font.py. Не редактировать вручную. */",
        '#include "icons.h"',
        "",
    ]
    for name, src in ICONS.items():
        cols = rows_to_columns(src.split("|"))
        out.append(f"static const uint8_t icon_{name}_cols[{len(cols)}] = {{{fmt_bytes(cols)}}};")
    out.append("")
    for name, src in ICONS.items():
        w = len(src.split("|")[0])
        out.append(f"const icon_t icon_{name} = {{{w}, icon_{name}_cols}};")
    out.append("")
    (ROOT / "src/fonts/icons_data.c").write_text("\n".join(out), encoding="utf-8")

    hdr = [
        "/* АВТОГЕНЕРАЦИЯ: tools/gen_font.py. Не редактировать вручную. */",
        "#ifndef ICONS_H",
        "#define ICONS_H",
        "",
        "#include <stdint.h>",
        "",
        "/* Иконка высотой 8 px: width столбцов, бит 0 — верхний пиксель. */",
        "typedef struct {",
        "    uint8_t width;",
        "    const uint8_t *cols;",
        "} icon_t;",
        "",
    ]
    for name in ICONS:
        hdr.append(f"extern const icon_t icon_{name};")
    hdr += ["", "#endif /* ICONS_H */", ""]
    (ROOT / "src/fonts/icons.h").write_text("\n".join(hdr), encoding="utf-8")


if __name__ == "__main__":
    n_extra = gen_font()
    gen_icons()
    print(f"font: 95 ascii + 64 cyr + {n_extra} extra; icons: {len(ICONS)}")
